import { createHmac, timingSafeEqual, randomBytes } from 'crypto'

export interface UploadCapabilityPayload {
  bucket: string
  path: string
  userId?: string | null
  email?: string | null
  iat: number
  exp: number
  nonce: string
}

function getSecretKey(): string {
  const secret =
    process.env.UPLOAD_CAPABILITY_SECRET ||
    process.env.SUPABASE_SERVICE_ROLE_KEY ||
    (process.env.NODE_ENV === 'test' || process.env.NODE_ENV === 'development'
      ? 'development-fallback-upload-capability-secret-key-32chars!'
      : null)

  if (!secret) {
    throw new Error('Server secret is not configured for upload capability tokens')
  }
  return secret
}

/**
 * Extracts and canonicalizes an inquiry storage path from a full URL, relative path, or filename.
 * Strips bucket prefixes, leading slashes, and query parameters.
 */
export function extractCanonicalInquiryPath(urlOrPath: string): string {
  if (!urlOrPath || typeof urlOrPath !== 'string') return ''
  let cleaned = urlOrPath.trim()
  if (cleaned.includes('inquiry-documents/')) {
    cleaned = cleaned.split('inquiry-documents/').pop() || cleaned
  }
  return cleaned.replace(/^\/+/, '').split('?')[0]
}

/**
 * Strict regex for inquiry document paths:
 * Formats: "prds/<filename>.<ext>" or "<filename>.<ext>"
 * Disallows traversal, encoded characters, and unwhitelisted extensions.
 */
export const SAFE_INQUIRY_PATH_REGEX =
  /^([a-zA-Z0-9_-]+\/)*[a-zA-Z0-9_-]+\.(pdf|doc|docx|txt|jpg|jpeg|png|gif|webp)$/i

/**
 * Issues a cryptographically signed upload capability token (HMAC-SHA256).
 * Binds the uploaded storage object to the server-verified upload event, bucket, path,
 * and optionally the submitter's verified user ID or email.
 */
export function issueUploadCapability(params: {
  bucket: string
  path: string
  userId?: string | null
  email?: string | null
  ttlSeconds?: number
}): string {
  const canonicalPath = extractCanonicalInquiryPath(params.path)
  const iat = Math.floor(Date.now() / 1000)
  const exp = iat + (params.ttlSeconds ?? 7200) // Default 2 hours validity

  const payload: UploadCapabilityPayload = {
    bucket: params.bucket,
    path: canonicalPath,
    userId: params.userId || null,
    email: params.email ? params.email.trim().toLowerCase() : null,
    iat,
    exp,
    nonce: randomBytes(16).toString('hex'),
  }

  const payloadStr = Buffer.from(JSON.stringify(payload)).toString('base64url')
  const signature = createHmac('sha256', getSecretKey())
    .update(`upload_cap:${payloadStr}`)
    .digest('base64url')

  return `${payloadStr}.${signature}`
}

/**
 * Verifies a server-issued upload capability token.
 * Ensures the token was generated by the server, has not expired, matches the canonical bucket
 * and object key, and matches user/email ownership if present.
 */
export function verifyUploadCapability(
  token: string | null | undefined,
  expected: {
    bucket: string
    path: string
    userId?: string | null
    email?: string | null
  }
): { valid: boolean; reason?: string; payload?: UploadCapabilityPayload } {
  if (!token || typeof token !== 'string') {
    return { valid: false, reason: 'Missing upload capability token' }
  }

  const parts = token.trim().split('.')
  if (parts.length !== 2) {
    return { valid: false, reason: 'Malformed upload capability token structure' }
  }

  const [payloadStr, signature] = parts
  let expectedSignature: string
  try {
    expectedSignature = createHmac('sha256', getSecretKey())
      .update(`upload_cap:${payloadStr}`)
      .digest('base64url')
  } catch {
    return { valid: false, reason: 'Server error generating signature check' }
  }

  const sigBuffer = Buffer.from(signature)
  const expectedSigBuffer = Buffer.from(expectedSignature)

  if (sigBuffer.length !== expectedSigBuffer.length || !timingSafeEqual(sigBuffer, expectedSigBuffer)) {
    return { valid: false, reason: 'Invalid upload capability token signature' }
  }

  let payload: UploadCapabilityPayload
  try {
    payload = JSON.parse(Buffer.from(payloadStr, 'base64url').toString('utf-8'))
  } catch {
    return { valid: false, reason: 'Invalid token payload' }
  }

  const now = Math.floor(Date.now() / 1000)
  if (payload.exp && payload.exp < now) {
    return { valid: false, reason: 'Upload capability token has expired' }
  }

  if (payload.bucket !== expected.bucket) {
    return { valid: false, reason: `Token bucket mismatch (expected: ${expected.bucket}, got: ${payload.bucket})` }
  }

  const canonicalPayloadPath = extractCanonicalInquiryPath(payload.path)
  const canonicalExpectedPath = extractCanonicalInquiryPath(expected.path)

  if (canonicalPayloadPath !== canonicalExpectedPath) {
    return { valid: false, reason: 'Token object path does not match referenced document' }
  }

  // If token is bound to a specific email, verify match
  if (payload.email && expected.email) {
    if (payload.email.toLowerCase() !== expected.email.trim().toLowerCase()) {
      return { valid: false, reason: 'Token email does not match submitting caller email' }
    }
  }

  // If token is bound to a specific user ID, verify match
  if (payload.userId && expected.userId) {
    if (payload.userId !== expected.userId) {
      return { valid: false, reason: 'Token user ID does not match submitting user' }
    }
  }

  return { valid: true, payload }
}

